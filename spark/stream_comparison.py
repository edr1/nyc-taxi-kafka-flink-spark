import glob,json
from pyspark.sql import SparkSession,functions as F,Window
spark=SparkSession.builder.appName('NYC Taxi Replay Comparison').master('local[*]').getOrCreate()
files=glob.glob('/app/results/lake/ingest_date=*/*.parquet')
if not files:raise SystemExit('No hay eventos persistidos; ejecute lake-writer y producer primero')
zones=glob.glob('/app/data/reference/*.csv')
if not zones:raise SystemExit('Falta Taxi Zone Lookup CSV')
lake=spark.read.parquet(*files)
# Spark lee el JSON original, conservando todas las columnas originales.
events=spark.read.json(lake.rdd.map(lambda r:r.payload_json))
z=spark.read.option('header',True).option('inferSchema',True).csv(zones[0])
enriched=events.join(F.broadcast(z.select(F.col('LocationID').alias('PULocationID'),'Borough','Zone')),'PULocationID','left')
agg=enriched.groupBy('Borough','Zone').agg(F.count('*').alias('replayed_trips'))
rank=agg.withColumn('rank',F.row_number().over(Window.partitionBy('Borough').orderBy(F.desc('replayed_trips'),F.asc('Zone'))))
rank.filter('rank <= 3').orderBy('Borough','rank').coalesce(1).write.mode('overwrite').option('header',True).csv('/app/results/comparison/replayed_top3')
rank.filter('rank <= 3').show(30,False)
hist=spark.read.option('header',True).option('inferSchema',True).csv('/app/results/batch/p7_top3')
current=rank.filter('rank <= 3').select('Borough',F.col('PULocationID') if 'PULocationID' in rank.columns else F.col('Zone'),F.col('rank').alias('replay_rank'))
hist3=hist.select('Borough','Zone',F.col('rank').alias('historical_rank'))
comparison=current.join(hist3,['Borough','Zone'],'full_outer')
comparison.coalesce(1).write.mode('overwrite').option('header',True).csv('/app/results/comparison/rank_overlap')
comparison.show(30,False)
print('ADVERTENCIA: ranking de eventos reproducidos, no equivale a una ventana de Flink.')
spark.stop()
